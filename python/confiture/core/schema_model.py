"""The one model of what a schema declares: tables, types, sequences, routines and views.

Every reader of a DDL tree answers in these types, and each is defined here once.
A second model of a table is how a fact one reader models and another does not
reaches an artefact — a primary key declared at table level read as a nullable
column, a generated DDL file that loses a column's identity.

The module is data and nothing else. It imports no parser and no database driver,
so a tool that only has to *hold* a schema — a seed generator, a parity fixture —
pays for neither. Everything is frozen: a model is a statement of what a tree
declares, and a reader that wants a different one builds a different one.

Two fields about a type, deliberately (#275). ``type_key`` is the **identity**,
``type_lattice.canonical_type`` of the parser's spelling, and decides whether two
columns hold one type. ``raw_sql_type`` is the **spelling** generated DDL writes:
the readable keyword with the typmod the author wrote (``VARCHAR(50)``), because
the length lives in the spelling. ``type_text`` is a third reading — the type as
the author wrote it — which is what a finding prints.

Identity is ``(schema, name)`` with a missing qualifier folded to
:data:`~confiture.core.schema_identity.DEFAULT_SCHEMA` (#313). The spelling never
invents a qualifier: :attr:`Table.qualified` prints what the author wrote.

A routine's identity adds its input argument types, and they are two fields for
the same reason a column's type is: :attr:`Routine.signature` is the spelling a
finding prints, :attr:`Routine.signature_key` the ``(schema, canonical type)`` per
argument that decides whether two routines are one. Compare keys through
``inventory.signatures_match``: a type schema written on one side and left off the
other still matches (#302), which no dict key can express — so a routine's
:class:`ObjectRef` is a bucket, and :attr:`SchemaModel.routines` holds every
overload that falls in it.
"""

from __future__ import annotations

import json
import re
from collections.abc import Callable, Iterator, Mapping
from dataclasses import asdict, dataclass, field, fields, replace
from typing import Any, Literal, TypeVar

from confiture.core.schema_identity import DEFAULT_SCHEMA

#: What a constraint that is not a column property enforces.
ConstraintKind = Literal["primary_key", "unique", "check", "foreign_key"]

#: ``GENERATED ALWAYS AS IDENTITY`` or ``GENERATED BY DEFAULT AS IDENTITY``.
IdentityKind = Literal["always", "by default"]

#: ``DEFERRABLE INITIALLY IMMEDIATE`` / ``… DEFERRED``; ``None`` is ``NOT DEFERRABLE``.
Deferral = Literal["immediate", "deferred"]

#: How a generated column holds its value. ``virtual`` arrived with PostgreSQL 18,
#: where it is also what ``GENERATED ALWAYS AS (…)`` with neither keyword means.
GeneratedKind = Literal["stored", "virtual"]

#: What ``CREATE FUNCTION``, ``CREATE PROCEDURE`` and ``CREATE AGGREGATE`` define.
RoutineKind = Literal["function", "procedure", "aggregate"]

#: What PostgreSQL records a routine may do; ``volatile`` when nothing is written.
Volatility = Literal["immutable", "stable", "volatile"]

#: A routine's input argument types, each as ``(schema, canonical name)``: the
#: schema is ``None`` where the argument named none, which matches any (#302).
Signature = tuple[tuple[str | None, str], ...]


@dataclass(frozen=True)
class ObjectRef:
    """A **bucket**: what makes two ``CREATE`` statements *candidates* for one object.

    ``schema`` is folded and defaulted, so an unqualified ``CREATE VIEW v`` and
    ``CREATE VIEW public.v`` are one object — what
    :data:`~confiture.core.schema_identity.DEFAULT_SCHEMA` is for. ``name`` is
    folded for the same reason; :attr:`display` keeps the spelling a change
    prints.

    ``signature`` is the inventory's :func:`~confiture.core.linting.inventory.signature_bucket`
    — the canonical *names* of a routine's input parameter types, without their
    own schemas. It is deliberately not the full signature: a dict key cannot
    express "a type schema written on one side and left off the other still
    matches", so ``fn(bigint)`` and ``fn(int8)`` must land in one bucket and
    :func:`~confiture.core.linting.inventory.signatures_match` decides inside it.
    Keyed on the full signature, one respelled routine would report as an added
    and a dropped function (#275).
    """

    kind: str
    schema: str
    name: str
    signature: tuple[str, ...] | None
    #: The spelling a change prints. Out of the key deliberately: it carries the
    #: *signature as written*, and ``fn(bigint)`` and ``fn(int8)`` are one
    #: routine written two ways (#275). Keyed on it, a respelled type would report
    #: as a dropped and an added function.
    display: str = field(compare=False)

    @property
    def qualified(self) -> str:
        """How a change names the object: the spelling the author wrote."""
        return self.display


def ref_for(kind: str, schema: str | None, name: str) -> ObjectRef:
    """The bucket of a relation-like object: ``(kind, folded schema, name)``, no signature."""
    return ObjectRef(
        kind=kind,
        schema=(schema or DEFAULT_SCHEMA).lower(),
        name=name,
        signature=None,
        display=qualified_name(schema, name),
    )


def qualified_name(schema: str | None, name: str) -> str:
    """``schema.name`` when the author wrote a schema, the bare name when they did not."""
    return f"{schema}.{name}" if schema else name


@dataclass(frozen=True)
class Column:
    """A column, whole.

    ``name`` keeps the author's case with quoting stripped, and ``folded`` is the
    parser's spelling; ``line`` is where the name is written, which is what a
    finding points at. ``not_null`` is what PostgreSQL will record: ``NOT NULL``,
    a primary key — on the column or at table level — and an identity column all
    set it. ``default`` is the default expression's text, ``identity`` the kind
    of ``GENERATED … AS IDENTITY``, ``generated`` the expression of a
    ``GENERATED ALWAYS AS (…)`` column and ``generated_kind`` how it is held.
    """

    name: str
    folded: str
    line: int
    type_text: str | None = None
    type_key: str | None = None
    raw_sql_type: str | None = None
    not_null: bool = False
    default: str | None = None
    identity: IdentityKind | None = None
    generated: str | None = None
    generated_kind: GeneratedKind | None = None
    primary_key: bool = False


#: ``serial`` and its siblings are not types: PostgreSQL stores an integer, NOT NULL,
#: a ``nextval`` default and a sequence the column owns, none of which DDL wrote.
SERIAL_TYPES = frozenset({"SMALLSERIAL", "SERIAL", "BIGSERIAL"})


@dataclass(frozen=True)
class Constraint:
    """A table constraint: a primary key, a UNIQUE, a CHECK or a foreign key.

    ``name`` is empty when the schema wrote none — PostgreSQL generates one at
    apply time, and nothing here invents it. ``columns`` are the columns it
    covers, whichever of the three places the grammar allows it was written in;
    ``ref_table`` / ``ref_columns`` / ``on_delete`` / ``on_update`` describe a
    foreign key, and an empty ``ref_columns`` means the referenced primary key.
    ``expression`` is a CHECK's condition, rendered.
    """

    kind: ConstraintKind
    name: str = ""
    columns: tuple[str, ...] = ()
    ref_table: str | None = None
    ref_columns: tuple[str, ...] = ()
    on_delete: str | None = None
    on_update: str | None = None
    expression: str | None = None
    deferrable: Deferral | None = None


@dataclass(frozen=True)
class Index:
    """An index on one table.

    ``columns`` holds each key as written — a column name or a rendered
    expression. ``method`` is the access method; PostgreSQL's grammar fills in
    ``btree`` when the statement writes no ``USING``, and so does the catalog.
    ``backs_constraint`` is set on an index that exists only to back a PRIMARY KEY,
    UNIQUE or EXCLUDE constraint — PostgreSQL's, never declared by DDL, so it is
    never *extra* to it; only the catalog knows it. ``key_options`` runs alongside
    ``columns``: what each key's element writes after the key — its collation,
    operator class and ordering (``gin_trgm_ops``, ``DESC NULLS LAST``), ``""``
    for a key that writes none, and ``()`` when no key writes any.
    """

    name: str | None
    table: str
    columns: tuple[str, ...]
    unique: bool = False
    where: str | None = None
    method: str | None = None
    backs_constraint: bool = False
    key_options: tuple[str, ...] = ()


@dataclass(frozen=True)
class Table:
    """A table: its columns, its constraints and its indexes."""

    name: str
    schema: str | None = None
    columns: tuple[Column, ...] = ()
    constraints: tuple[Constraint, ...] = ()
    indexes: tuple[Index, ...] = ()

    @property
    def qualified(self) -> str:
        return qualified_name(self.schema, self.name)

    def column(self, folded: str) -> Column | None:
        """The column the parser spells *folded*, or ``None``."""
        return next((column for column in self.columns if column.folded == folded), None)

    def constraints_of(self, kind: ConstraintKind) -> tuple[Constraint, ...]:
        """The table's constraints of one kind, in the order the tree declared them."""
        return tuple(constraint for constraint in self.constraints if constraint.kind == kind)


@dataclass(frozen=True)
class EnumType:
    """``CREATE TYPE … AS ENUM``: its labels, in declaration order."""

    name: str
    schema: str | None = None
    values: tuple[str, ...] = ()

    @property
    def qualified(self) -> str:
        return qualified_name(self.schema, self.name)


@dataclass(frozen=True)
class Sequence:
    """``CREATE SEQUENCE``, with the options a comparison reads."""

    name: str
    schema: str | None = None
    start: int | None = None
    increment: int | None = None
    min_value: int | None = None
    max_value: int | None = None

    @property
    def qualified(self) -> str:
        return qualified_name(self.schema, self.name)


@dataclass(frozen=True)
class Routine:
    """One routine — a function, a procedure or an aggregate — and one overload of it.

    ``signature`` is the input argument types as the reader found them written —
    the DDL's own words, or ``format_type``'s — and ``signature_key`` the same
    types canonicalised, which is what makes two routines one. ``OUT`` and
    ``TABLE`` parameters are in neither: PostgreSQL does not resolve a call by them.

    ``body`` is the text between the ``AS`` quotes, as written, and ``None`` where
    that text is not SQL (``LANGUAGE c`` / ``internal``: a symbol). ``returns`` is
    the result type as the reader spells it, ``None`` for a procedure.
    ``security_definer``, ``search_path_pinned`` and ``volatility`` are what
    PostgreSQL records — invoker, unpinned and ``volatile`` when nothing is written.
    """

    name: str
    schema: str | None = None
    kind: RoutineKind = "function"
    signature: str = ""
    signature_key: Signature = ()
    returns: str | None = None
    language: str | None = None
    body: str | None = None
    security_definer: bool = False
    search_path_pinned: bool = False
    volatility: Volatility = "volatile"

    @property
    def qualified(self) -> str:
        return qualified_name(self.schema, self.name)

    @property
    def identity(self) -> str:
        """``schema.name(arguments)``, spelled as the reader found it."""
        return f"{self.qualified}({self.signature})"


@dataclass(frozen=True)
class View:
    """A view or a materialized view.

    ``definition`` is the query as the reader holds it: the DDL's ``SELECT``
    rendered, or ``pg_get_viewdef``'s deparse — two spellings of one query, which
    is why a definition is compared through one deparser or not at all.
    ``indexes`` are a materialized view's; a view has none.
    """

    name: str
    schema: str | None = None
    materialized: bool = False
    definition: str | None = None
    indexes: tuple[Index, ...] = ()

    @property
    def kind(self) -> str:
        return "matview" if self.materialized else "view"

    @property
    def qualified(self) -> str:
        return qualified_name(self.schema, self.name)


@dataclass(frozen=True)
class Trigger:
    """A trigger a user created, named with the table it fires on.

    A trigger's name is unique per *table*, not per schema, so its identity is
    ``(schema, table, name)``: two tables may each carry a ``trg_touch``.
    """

    name: str
    table: str
    schema: str | None = None

    @property
    def qualified(self) -> str:
        """``schema.table.trigger``, the schema only where it was written."""
        return f"{qualified_name(self.schema, self.table)}.{self.name}"


@dataclass(frozen=True)
class ColumnReference:
    """What a foreign key column points at: the table, found, and the column in it.

    ``table`` is the table the model holds when it holds it — a bare name found
    wherever ``search_path`` put it — and otherwise the reference as identity
    reads it. ``column`` is the referenced column; ``None`` where the key names
    none and the model does not hold the target's primary key to say which.
    """

    table: ObjectRef
    column: str | None


@dataclass(frozen=True)
class ColumnFacts:
    """What a writer supplying one column must respect.

    ``type_key`` / ``raw_sql_type`` / ``not_null`` / ``default`` are the column's.
    ``unique`` is true where one PRIMARY KEY, UNIQUE constraint or unique index
    covers this column alone — declared on the column, at table level or as an
    index. ``checks`` are the CHECK expressions that name it, ``enum_values`` the
    labels of the enum its type is, ``foreign_key`` what it references.
    """

    name: str
    type_key: str | None
    raw_sql_type: str | None
    not_null: bool
    default: str | None
    unique: bool
    checks: tuple[str, ...] = ()
    enum_values: tuple[str, ...] | None = None
    foreign_key: ColumnReference | None = None


def routine_ref(routine: Routine) -> ObjectRef:
    """The bucket of a routine: its kind, folded schema, name and argument type names."""
    return ObjectRef(
        kind=routine.kind,
        schema=(routine.schema or DEFAULT_SCHEMA).lower(),
        name=routine.name,
        signature=tuple(name for _schema, name in routine.signature_key),
        display=routine.identity,
    )


def view_ref(view: View) -> ObjectRef:
    """The bucket of a view or a materialized view."""
    return ref_for(view.kind, view.schema, view.name)


def trigger_ref(trigger: Trigger) -> ObjectRef:
    """The bucket of a trigger: its schema, and its table and name together."""
    return ref_for("trigger", trigger.schema, f"{trigger.table}.{trigger.name}")


_K = TypeVar("_K")
_V = TypeVar("_V")


class _ReadOnly(Mapping[_K, _V]):
    """A mapping nothing writes to: a copy of what the model was built from.

    Not ``MappingProxyType``, which cannot be copied or pickled: a caller that
    deep-copies a model, or hands one to another process, gets it whole.
    """

    __slots__ = ("_data",)

    def __init__(self, data: Mapping[_K, _V]) -> None:
        self._data = dict(data)

    def __getitem__(self, key: _K) -> _V:
        return self._data[key]

    def __iter__(self) -> Iterator[_K]:
        return iter(self._data)

    def __len__(self) -> int:
        return len(self._data)

    def __repr__(self) -> str:
        return repr(self._data)


@dataclass(frozen=True)
class SchemaModel:
    """Everything one schema declares, each object under its :class:`ObjectRef`.

    A routine's reference is a bucket (see :func:`routine_ref`), so
    :attr:`routines` maps it to every overload in it, in declaration order.
    Frozen through and through: each mapping is a read-only copy of the one it
    was built from, so neither a reader nor the builder can change a model after
    it is made.
    """

    tables: Mapping[ObjectRef, Table] = field(default_factory=dict)
    enum_types: Mapping[ObjectRef, EnumType] = field(default_factory=dict)
    sequences: Mapping[ObjectRef, Sequence] = field(default_factory=dict)
    routines: Mapping[ObjectRef, tuple[Routine, ...]] = field(default_factory=dict)
    views: Mapping[ObjectRef, View] = field(default_factory=dict)
    triggers: Mapping[ObjectRef, Trigger] = field(default_factory=dict)

    def __post_init__(self) -> None:
        for mapping in fields(self):
            value = getattr(self, mapping.name)
            if not isinstance(value, _ReadOnly):
                object.__setattr__(self, mapping.name, _ReadOnly(value))

    def all_routines(self) -> list[Routine]:
        """Every routine, overloads included, in identity order."""
        return [routine for _, found in _ordered(self.routines) for routine in found]

    def to_dict(self) -> dict[str, Any]:
        """A JSON-ready rendering, objects in identity order, for goldens and dumps."""

        def section(objects: Mapping[ObjectRef, Any]) -> list[dict[str, Any]]:
            return [asdict(obj) for _, obj in _ordered(objects)]

        return {
            "tables": section(self.tables),
            "enum_types": section(self.enum_types),
            "sequences": section(self.sequences),
            "routines": [asdict(routine) for routine in self.all_routines()],
            "views": section(self.views),
            "triggers": section(self.triggers),
        }

    def to_json(self) -> str:
        """The model's wire: :meth:`to_dict`, keys sorted, so one model is one text.

        ``schema-model.schema.json`` publishes its shape. Sorted keys make the bytes
        a function of the model alone, not of the order fields are declared in.
        """
        return json.dumps(self.to_dict(), indent=2, sort_keys=True)

    @staticmethod
    def from_json(text: str) -> SchemaModel:
        """The model :meth:`to_json` wrote *text* from.

        Each object's reference is derived from the object, as every reader derives
        it — a table's from its schema and name, a routine's from its signature — so
        the wire carries no key a reader could disagree with.
        """
        return _model_from_dict(json.loads(text))


def _ordered(objects: Mapping[ObjectRef, Any]) -> list[tuple[ObjectRef, Any]]:
    return sorted(
        objects.items(),
        key=lambda item: (item[0].schema, item[0].name, item[0].kind, item[0].signature or ()),
    )


def _column_from(data: dict[str, Any]) -> Column:
    return Column(**data)


def _constraint_from(data: dict[str, Any]) -> Constraint:
    return Constraint(
        **{**data, "columns": tuple(data["columns"]), "ref_columns": tuple(data["ref_columns"])}
    )


def _index_from(data: dict[str, Any]) -> Index:
    """An index from its wire; one written before ``key_options`` existed reads as none."""
    return Index(
        **{
            **data,
            "columns": tuple(data["columns"]),
            "key_options": tuple(data.get("key_options", ())),
        }
    )


def _table_from(data: dict[str, Any]) -> Table:
    return Table(
        **{
            **data,
            "columns": tuple(_column_from(c) for c in data["columns"]),
            "constraints": tuple(_constraint_from(c) for c in data["constraints"]),
            "indexes": tuple(_index_from(i) for i in data["indexes"]),
        }
    )


def _routine_from(data: dict[str, Any]) -> Routine:
    key = tuple((schema, name) for schema, name in data["signature_key"])
    return Routine(**{**data, "signature_key": key})


def _view_from(data: dict[str, Any]) -> View:
    return View(**{**data, "indexes": tuple(_index_from(i) for i in data["indexes"])})


_T = TypeVar("_T")


def _keyed(
    items: list[dict[str, Any]],
    read: Callable[[dict[str, Any]], _T],
    ref: Callable[[_T], ObjectRef],
) -> dict[ObjectRef, _T]:
    return {ref(obj): obj for obj in map(read, items)}


def _model_from_dict(data: dict[str, Any]) -> SchemaModel:
    routines: dict[ObjectRef, list[Routine]] = {}
    for routine in map(_routine_from, data["routines"]):
        routines.setdefault(routine_ref(routine), []).append(routine)
    return SchemaModel(
        tables=_keyed(data["tables"], _table_from, lambda t: ref_for("table", t.schema, t.name)),
        enum_types=_keyed(
            data["enum_types"],
            lambda d: EnumType(**{**d, "values": tuple(d["values"])}),
            lambda e: ref_for("type", e.schema, e.name),
        ),
        sequences=_keyed(
            data["sequences"],
            lambda d: Sequence(**d),
            lambda s: ref_for("sequence", s.schema, s.name),
        ),
        routines={ref: tuple(found) for ref, found in routines.items()},
        views=_keyed(data["views"], _view_from, view_ref),
        triggers=_keyed(data["triggers"], lambda d: Trigger(**d), trigger_ref),
    )


