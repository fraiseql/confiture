#: What a constraint that is not a column property enforces.
ConstraintKind = Literal["primary_key", "unique", "check", "foreign_key", "exclusion"]

#: ``GENERATED ALWAYS AS IDENTITY`` or ``GENERATED BY DEFAULT AS IDENTITY``.
IdentityKind = Literal["always", "by default"]

#: ``DEFERRABLE INITIALLY IMMEDIATE`` / ``… DEFERRED``; ``None`` is ``NOT DEFERRABLE``.
Deferral = Literal["immediate", "deferred"]

#: How a generated column holds its value. ``virtual`` arrived with PostgreSQL 18,
#: where it is also what ``GENERATED ALWAYS AS (…)`` with neither keyword means.
GeneratedKind = Literal["stored", "virtual"]

#: What a column's default is, as the reader that held its parse tree classified it:
#: a ``nextval(…)``, a call to a value generator (``gen_random_uuid()``, ``uuidv7()``,
#: …), a constant, or any other expression.
DefaultKind = Literal["sequence", "generator", "constant", "expression"]


class ValueSource(StrEnum):
    """Where a column's value comes from when a row is written.

    One answer for every reader that asks — a seed writer (which columns it
    supplies), parity (what a ``serial`` is in the catalog), drift (whose default
    is its own) and the tenant rules (which keys cannot collide) — derived from
    the column's own fields, never from its default's text.
    """

    IDENTITY = "identity"
    GENERATED = "generated"
    SEQUENCE = "sequence"
    GENERATOR = "generator"
    EXPRESSION = "expression"
    CONSTANT = "constant"
    NONE = "none"

    @property
    def filled_by_postgresql(self) -> bool:
        """PostgreSQL writes the value; a writer does not supply it (``writable_columns``)."""
        return self in (ValueSource.IDENTITY, ValueSource.GENERATED, ValueSource.SEQUENCE)

    @property
    def unique_without_author_input(self) -> bool:
        """Every row gets a value no other row has, whatever the writer does."""
        return self in (ValueSource.IDENTITY, ValueSource.SEQUENCE, ValueSource.GENERATOR)


#: What ``CREATE FUNCTION``, ``CREATE PROCEDURE`` and ``CREATE AGGREGATE`` define.
RoutineKind = Literal["function", "procedure", "aggregate"]

#: What PostgreSQL records a routine may do; ``volatile`` when nothing is written.
Volatility = Literal["immutable", "stable", "volatile"]

#: A routine's input argument types, each as ``(schema, canonical name)``: the
#: schema is ``None`` where the argument named none, which matches any (#302).
Signature = tuple[tuple[str | None, str], ...]


@dataclass(frozen=True)
class ObjectRef:
    """A **bucket**: what makes two ``CREATE`` statements *candidates* for one object.

    ``schema`` is folded and defaulted, so an unqualified ``CREATE VIEW v`` and
    ``CREATE VIEW public.v`` are one object — what
    :data:`~confiture.core.schema_identity.DEFAULT_SCHEMA` is for. ``name`` is
    folded for the same reason; :attr:`display` keeps the spelling a change
    prints.

    ``signature`` is the inventory's :func:`~confiture.core.linting.inventory.signature_bucket`
    — the canonical *names* of a routine's input parameter types, without their
    own schemas. It is deliberately not the full signature: a dict key cannot
    express "a type schema written on one side and left off the other still
    matches", so ``fn(bigint)`` and ``fn(int8)`` must land in one bucket and
    :func:`~confiture.core.linting.inventory.signatures_match` decides inside it.
    Keyed on the full signature, one respelled routine would report as an added
    and a dropped function (#275).
    """

    kind: str
    schema: str
    name: str
    signature: tuple[str, ...] | None
    #: The spelling a change prints. Out of the key deliberately: it carries the
    #: *signature as written*, and ``fn(bigint)`` and ``fn(int8)`` are one
    #: routine written two ways (#275). Keyed on it, a respelled type would report
    #: as a dropped and an added function.
    display: str = field(compare=False)

    @property
    def qualified(self) -> str:
        """How a change names the object: the spelling the author wrote."""
        return self.display


def ref_for(kind: str, schema: str | None, name: str) -> ObjectRef:
    """The bucket of a relation-like object: ``(kind, folded schema, name)``, no signature."""
    return ObjectRef(
        kind=kind,
        schema=(schema or DEFAULT_SCHEMA).lower(),
        name=name,
        signature=None,
        display=qualified_name(schema, name),
    )


def qualified_name(schema: str | None, name: str) -> str:
    """``schema.name`` when the author wrote a schema, the bare name when they did not."""
    return f"{schema}.{name}" if schema else name


@dataclass(frozen=True)
class RelationName:
    """A relation one object names — a foreign key's target, an index's table, a parent.

    Two parts, never one string (#478). PostgreSQL accepts a dot inside a quoted
    name (``app."a.b"``), so ``schema.name`` text cannot be taken apart again: the
    parser hands the two over separately, the catalog reads them separately, and
    they stay that way. Both parts are as the parser holds them — an unquoted
    part already folded, a quoted one kept — and ``schema`` is ``None`` when the
    author wrote none; :attr:`identity` defaults it, which is how two references
    are compared.
    """

    schema: str | None
    name: str

    @property
    def identity(self) -> tuple[str, str]:
        """``(schema, name)`` the relation is found under: a missing schema defaulted."""
        return self.schema or DEFAULT_SCHEMA, self.name

    @property
    def qualified(self) -> str:
        """``schema.name`` as written, for a message — never to be split again."""
        return qualified_name(self.schema, self.name)

    def ref(self, kind: str = "table") -> ObjectRef:
        """The model's key of the relation, as :func:`ref_for` builds it."""
        return ref_for(kind, self.schema, self.name)


@dataclass(frozen=True)
class Column:
    """A column, whole.

    ``name`` keeps the author's case with quoting stripped, and ``folded`` is the
    parser's spelling; ``file`` and ``line`` are where the name is written — the
    file that wrote the column, which an ``ALTER … ADD COLUMN`` makes another
    than its table's, and the line in it — which is what a finding points at.
    Where a column is written is not what it is: two trees declaring one column
    from different files declare one column, so neither takes part in equality. ``not_null`` is what PostgreSQL will record: ``NOT NULL``,
    a primary key — on the column or at table level — and an identity column all
    set it. ``default`` is the default expression's text, ``identity`` the kind
    of ``GENERATED … AS IDENTITY``, ``generated`` the expression of a
    ``GENERATED ALWAYS AS (…)`` column and ``generated_kind`` how it is held.
    """

    name: str
    folded: str
    line: int = field(compare=False)
    type_text: str | None = None
    type_key: str | None = None
    raw_sql_type: str | None = None
    not_null: bool = False
    default: str | None = None
    identity: IdentityKind | None = None
    generated: str | None = None
    generated_kind: GeneratedKind | None = None
    primary_key: bool = False
    file: str | None = field(default=None, compare=False)
    #: What :attr:`default` is, read from its parse tree by the reader that held it.
    #: Derived from the default, so it takes no part in equality.
    default_kind: DefaultKind | None = field(default=None, compare=False)

    @property
    def value_source(self) -> ValueSource:
        """Where this column's value comes from (:class:`ValueSource`)."""
        if self.identity:
            return ValueSource.IDENTITY
        if self.generated is not None:
            return ValueSource.GENERATED
        if (self.raw_sql_type or "").upper() in SERIAL_TYPES:
            return ValueSource.SEQUENCE
        return ValueSource(self.default_kind) if self.default_kind else ValueSource.NONE


#: ``serial`` and its siblings are not types: PostgreSQL stores an integer, NOT NULL,
#: a ``nextval`` default and a sequence the column owns, none of which DDL wrote.
SERIAL_TYPES = frozenset({"SMALLSERIAL", "SERIAL", "BIGSERIAL"})


@dataclass(frozen=True)
class Constraint:
    """A table constraint: a primary key, a UNIQUE, a CHECK, a foreign key or an EXCLUDE.

    ``name`` is empty when the schema wrote none — PostgreSQL generates one at
    apply time, and nothing here invents it. ``columns`` are the columns it
    covers, whichever of the three places the grammar allows it was written in;
    ``ref_table`` / ``ref_columns`` / ``on_delete`` / ``on_update`` describe a
    foreign key, and an empty ``ref_columns`` means the referenced primary key.
    ``expression`` is a CHECK's condition, rendered.

    An exclusion constraint's ``columns`` are its elements, each a column name or a
    rendered expression as an index's keys are, with ``key_options`` alongside as
    on :class:`Index`; ``operators`` runs alongside too, the operator each element
    is compared with (``&&``, ``OPERATOR(pg_catalog.=)``). ``method`` is its index
    access method and ``where`` its partial predicate, rendered.
    """

    kind: ConstraintKind
    name: str = ""
    columns: tuple[str, ...] = ()
    ref_table: RelationName | None = None
    ref_columns: tuple[str, ...] = ()
    on_delete: str | None = None
    on_update: str | None = None
    expression: str | None = None
    deferrable: Deferral | None = None
    operators: tuple[str, ...] = ()
    method: str | None = None
    where: str | None = None
    key_options: tuple[str, ...] = ()


@dataclass(frozen=True)
class Index:
    """An index on one table.

    ``columns`` holds each key as written — a column name or a rendered
    expression. ``method`` is the access method; PostgreSQL's grammar fills in
    ``btree`` when the statement writes no ``USING``, and so does the catalog.
    ``backs_constraint`` is set on an index that exists only to back a PRIMARY KEY,
    UNIQUE or EXCLUDE constraint — PostgreSQL's, never declared by DDL, so it is
    never *extra* to it; only the catalog knows it. ``key_options`` runs alongside
    ``columns``: what each key's element writes after the key — its collation,
    operator class and ordering (``gin_trgm_ops``, ``DESC NULLS LAST``), ``""``
    for a key that writes none, and ``()`` when no key writes any.
    """

    name: str | None
    table: RelationName
    columns: tuple[str, ...]
    unique: bool = False
    where: str | None = None
    method: str | None = None
    backs_constraint: bool = False
    key_options: tuple[str, ...] = ()
    #: Alongside ``columns``: whether each key is an expression rather than a
    #: column. ``None`` where the reader recorded nothing (a model written
    #: before it did), and a key shaped like an identifier is then a column.
    expressions: tuple[bool, ...] | None = None


@dataclass(frozen=True)
class Table:
    """A table: its columns, its constraints and its indexes."""

    name: str
    schema: str | None = None
    columns: tuple[Column, ...] = ()
    constraints: tuple[Constraint, ...] = ()
    indexes: tuple[Index, ...] = ()

    @property
    def qualified(self) -> str:
        return qualified_name(self.schema, self.name)

    @property
    def relation(self) -> RelationName:
        """The table as another object names it: its schema and its name, apart."""
        return RelationName(self.schema, self.name)

    def column(self, folded: str) -> Column | None:
        """The column the parser spells *folded*, or ``None``."""
        return next((column for column in self.columns if column.folded == folded), None)

    def constraints_of(self, kind: ConstraintKind) -> tuple[Constraint, ...]:
        """The table's constraints of one kind, in the order the tree declared them."""
        return tuple(constraint for constraint in self.constraints if constraint.kind == kind)


