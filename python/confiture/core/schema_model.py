#: The prefix pg_tviews reads a ``CREATE TABLE … AS`` target by: ``tv_<entity>``.
TVIEW_PREFIX = "tv_"

#: The schema pg_tviews keeps every object of its own in, whatever ``search_path``
#: says (its control file's ``schema``, from 0.1.0-beta.20).
TVIEWS_SCHEMA = "tviews"


@dataclass(frozen=True)
class TView:
    """A pg_tviews TVIEW: ``CREATE TABLE tv_<entity> AS SELECT …``.

    pg_tviews turns that statement into a table, a backing view ``v_<entity>``
    and triggers on each base table, and lists it in ``tviews.registry``. The
    model holds the TVIEW as one object — its relation and its query — and its
    parts belong to it. ``definition`` is the query as the reader holds it: the
    DDL's ``SELECT`` rendered, or the registry's ``query``.

    ``logged`` and ``fillfactor`` are pg_tviews' ``options`` keys of those names:
    what the tree pins (``UNLOGGED``, ``WITH (fillfactor = n)``, ``SET LOGGED``),
    ``None`` where it pins nothing, or what the registry holds, every key set.
    """

    name: str
    schema: str | None = None
    definition: str | None = None
    logged: bool | None = None
    fillfactor: int | None = None

    @property
    def entity(self) -> str:
        return self.name.removeprefix(TVIEW_PREFIX)

    @property
    def backing_view(self) -> str:
        return f"v_{self.entity}"

    @property
    def qualified(self) -> str:
        return qualified_name(self.schema, self.name)


#: The pg_tviews ``options`` keys a tree can pin, as :class:`TView` holds them.
TVIEW_OPTIONS = ("logged", "fillfactor")


def tview_ref(tview: TView) -> ObjectRef:
    """The bucket of a TVIEW: its schema and its ``tv_*`` relation."""
    return ref_for("tview", tview.schema, tview.name)


def view_ref(view: View) -> ObjectRef:
    """The bucket of a view or a materialized view."""
    return ref_for(view.kind, view.schema, view.name)


def trigger_ref(trigger: Trigger) -> ObjectRef:
    """The bucket of a trigger: its schema, and its table and name together."""
    return ref_for("trigger", trigger.schema, f"{trigger.table}.{trigger.name}")


_K = TypeVar("_K")
_V = TypeVar("_V")


class _ReadOnly(Mapping[_K, _V]):
    """A mapping nothing writes to: a copy of what the model was built from.

    Not ``MappingProxyType``, which cannot be copied or pickled: a caller that
    deep-copies a model, or hands one to another process, gets it whole.
    """

    __slots__ = ("_data",)

    def __init__(self, data: Mapping[_K, _V]) -> None:
        self._data = dict(data)

    def __getitem__(self, key: _K) -> _V:
        return self._data[key]

    def __iter__(self) -> Iterator[_K]:
        return iter(self._data)

    def __len__(self) -> int:
        return len(self._data)

    def __repr__(self) -> str:
        return repr(self._data)


