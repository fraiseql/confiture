"""What a seed tree populates, and by which key its rows are matched across databases (#743).

A surrogate key PostgreSQL generates differs between a seed-built database and a
migrate-only one, so a key is only *stable* when every statement that adds rows
writes it. A foreign key to such a generated key is compared through the parent's
stable key, never by its number.
"""

from confiture.config.environment import SeedDriftSettings
from confiture.core.schema_model import RelationName
from confiture.core.schema_read import read_text
from confiture.core.seed.drift_scope import (
    Dereference,
    Field,
    ScopedTable,
    SeedScope,
    seed_scope,
)

TRINITY = """
CREATE SCHEMA catalog;
CREATE TABLE catalog.tb_unit (
    pk_unit bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    id uuid NOT NULL UNIQUE,
    identifier text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
"""


def _scope(ddl: str, seeds: dict[str, str], **settings: object) -> SeedScope:
    return seed_scope(
        list(seeds.items()), read_text(ddl), SeedDriftSettings.model_validate(settings)
    )


def _table(scope: SeedScope, qualified: str) -> ScopedTable:
    return next(t for t in scope.tables if t.relation.qualified == qualified)


class TestTargets:
    def test_every_written_table_is_in_scope(self) -> None:
        ddl = TRINITY + "CREATE TABLE catalog.tb_status (code text PRIMARY KEY, label text);\n"
        seeds = {
            "seeds/01.sql": "INSERT INTO catalog.tb_unit (id, identifier) VALUES "
            "('7c1f2a8e-0000-4000-8000-000000000001', 'kilogram');\n",
            "seeds/02.sql": "COPY catalog.tb_status (code, label) FROM stdin;\nok\tOK\n\\.\n",
        }

        scope = _scope(ddl, seeds)

        assert [t.relation.qualified for t in scope.tables] == [
            "catalog.tb_unit",
            "catalog.tb_status",
        ]
        assert scope.not_compared == ()

    def test_written_at_names_each_file_and_line(self) -> None:
        scope = _scope(
            TRINITY,
            {
                "seeds/01.sql": "-- units\nINSERT INTO catalog.tb_unit (id, identifier) VALUES ('a', 'b');\n"
            },
        )

        assert _table(scope, "catalog.tb_unit").written_at == ("seeds/01.sql:2",)

    def test_a_table_the_schema_does_not_declare_is_not_compared(self) -> None:
        scope = _scope(TRINITY, {"s.sql": "INSERT INTO catalog.tb_nope (id) VALUES (1);\n"})

        [entry] = scope.not_compared
        assert entry.table == "catalog.tb_nope"
        assert "the schema tree declares no such table" in entry.reason
        assert entry.where == "s.sql:1"

    def test_an_unparseable_seed_file_is_not_compared_never_dropped(self) -> None:
        scope = _scope(TRINITY, {"s.sql": "INSERT INTO catalog.tb_unit VALUES (;\n"})

        [entry] = scope.not_compared
        assert entry.where == "s.sql:1"
        assert "PostgreSQL's parser rejects" in entry.reason


class TestStagingResolution:
    DDL = (
        TRINITY
        + """
CREATE SCHEMA prep_seed;
CREATE TABLE prep_seed.tb_unit (id uuid, identifier text);
CREATE FUNCTION catalog.fn_resolve_tb_unit() RETURNS void LANGUAGE sql AS $$
    INSERT INTO catalog.tb_unit (id, identifier)
    SELECT id, identifier FROM prep_seed.tb_unit
$$;
"""
    )

    def test_a_staging_table_is_replaced_by_its_final_table(self) -> None:
        scope = _scope(
            self.DDL, {"s.sql": "INSERT INTO prep_seed.tb_unit VALUES ('a', 'kilogram');\n"}
        )

        table = _table(scope, "catalog.tb_unit")
        assert table.staging == RelationName("prep_seed", "tb_unit")
        assert table.key == (Field("id"),)
        assert table.columns == (Field("identifier"),)


class TestKeys:
    def test_a_unique_uuid_beside_an_identity_primary_key(self) -> None:
        scope = _scope(
            TRINITY,
            {"s.sql": "INSERT INTO catalog.tb_unit (id, identifier) VALUES ('a', 'b');\n"},
        )

        table = _table(scope, "catalog.tb_unit")
        assert (table.key, table.key_basis) == ((Field("id"),), "unique")

    def test_a_written_primary_key(self) -> None:
        ddl = "CREATE TABLE app.tb_status (code text PRIMARY KEY, label text);\n"
        scope = _scope(ddl, {"s.sql": "INSERT INTO app.tb_status VALUES ('ok', 'OK');\n"})

        table = _table(scope, "app.tb_status")
        assert (table.key, table.key_basis) == ((Field("code"),), "primary_key")

    def test_an_identity_by_default_every_seed_row_writes_is_stable(self) -> None:
        ddl = (
            "CREATE TABLE app.tb_k (pk_k bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
            " label text);\n"
        )
        scope = _scope(ddl, {"s.sql": "INSERT INTO app.tb_k (pk_k, label) VALUES (1, 'a');\n"})

        assert _table(scope, "app.tb_k").key == (Field("pk_k"),)

    def test_a_default_uuid_one_statement_omits_is_not_stable(self) -> None:
        ddl = "CREATE TABLE app.tb_k (id uuid PRIMARY KEY DEFAULT gen_random_uuid(), label text);\n"
        seeds = {
            "s.sql": "INSERT INTO app.tb_k (id, label) VALUES ('a', 'x');\n"
            "INSERT INTO app.tb_k (label) VALUES ('y');\n"
        }

        scope = _scope(ddl, seeds)

        [entry] = scope.not_compared
        assert entry.table == "app.tb_k"
        assert "no stable key" in entry.reason
        assert "seed_drift:" in entry.reason and "app.tb_k: {key: [<column>]}" in entry.reason

    def test_only_an_identity_primary_key_is_not_compared(self) -> None:
        ddl = "CREATE TABLE app.tb_k (pk_k bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, x text);\n"
        scope = _scope(ddl, {"s.sql": "INSERT INTO app.tb_k (x) VALUES ('a');\n"})

        assert [e.table for e in scope.not_compared] == ["app.tb_k"]

    def test_a_declared_key_wins(self) -> None:
        ddl = "CREATE TABLE app.tb_k (pk_k bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, iso text);\n"
        scope = _scope(
            ddl,
            {"s.sql": "INSERT INTO app.tb_k (iso) VALUES ('fr');\n"},
            tables={"app.tb_k": {"key": ["iso"]}},
        )

        table = _table(scope, "app.tb_k")
        assert (table.key, table.key_basis) == ((Field("iso"),), "declared")

    def test_a_composite_primary_key_is_a_tuple(self) -> None:
        ddl = "CREATE TABLE app.tb_pair (a text, b text, note text, PRIMARY KEY (a, b));\n"
        scope = _scope(ddl, {"s.sql": "INSERT INTO app.tb_pair VALUES ('x', 'y', 'z');\n"})

        assert _table(scope, "app.tb_pair").key == (Field("a"), Field("b"))


class TestColumns:
    def test_only_what_the_seed_writes_is_compared(self) -> None:
        scope = _scope(
            TRINITY,
            {"s.sql": "INSERT INTO catalog.tb_unit (id, identifier) VALUES ('a', 'b');\n"},
        )

        assert _table(scope, "catalog.tb_unit").columns == (Field("identifier"),)

    def test_an_insert_naming_no_columns_writes_every_writable_one_and_a_computed_one_is_not_compared(
        self,
    ) -> None:
        ddl = "CREATE TABLE app.tb_s (code text PRIMARY KEY, label text, at timestamptz DEFAULT now());\n"
        scope = _scope(ddl, {"s.sql": "INSERT INTO app.tb_s VALUES ('ok', 'OK', now());\n"})

        table = _table(scope, "app.tb_s")
        assert table.columns == (Field("label"),)
        assert table.uncompared == (
            ("at", "a seed row computes it (FuncCall), so it differs per database"),
        )

    def test_a_foreign_key_to_a_generated_key_is_dereferenced(self) -> None:
        ddl = (
            TRINITY
            + """
CREATE TABLE catalog.tb_conversion (
    id uuid PRIMARY KEY,
    fk_unit bigint NOT NULL REFERENCES catalog.tb_unit (pk_unit),
    factor numeric
);
"""
        )
        seeds = {
            "s.sql": "INSERT INTO catalog.tb_unit (id, identifier) VALUES ('u', 'kg');\n"
            "INSERT INTO catalog.tb_conversion (id, fk_unit, factor) VALUES ('c', 1, 1000);\n"
        }

        table = _table(_scope(ddl, seeds), "catalog.tb_conversion")

        deref = Dereference(RelationName("catalog", "tb_unit"), "pk_unit", ("id",))
        assert table.columns == (Field("fk_unit", deref), Field("factor"))

    def test_a_join_table_s_key_is_dereferenced_too(self) -> None:
        ddl = (
            TRINITY
            + """
CREATE TABLE catalog.tb_role (pk_role bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, code text UNIQUE NOT NULL);
CREATE TABLE catalog.tb_unit_role (
    fk_unit bigint REFERENCES catalog.tb_unit (pk_unit),
    fk_role bigint REFERENCES catalog.tb_role (pk_role),
    PRIMARY KEY (fk_unit, fk_role)
);
"""
        )
        seeds = {
            "s.sql": "INSERT INTO catalog.tb_unit (id, identifier) VALUES ('u', 'kg');\n"
            "INSERT INTO catalog.tb_role (code) VALUES ('admin');\n"
            "INSERT INTO catalog.tb_unit_role VALUES (1, 1);\n"
        }

        table = _table(_scope(ddl, seeds), "catalog.tb_unit_role")

        assert [f.via.parent.qualified for f in table.key if f.via] == [
            "catalog.tb_unit",
            "catalog.tb_role",
        ]

    def test_a_foreign_key_to_a_parent_with_no_stable_key_is_not_compared(self) -> None:
        ddl = """
CREATE TABLE app.tb_p (pk_p bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, label text);
CREATE TABLE app.tb_c (code text PRIMARY KEY, fk_p bigint REFERENCES app.tb_p (pk_p));
"""
        seeds = {"s.sql": "INSERT INTO app.tb_c VALUES ('x', 1);\n"}

        table = _table(_scope(ddl, seeds), "app.tb_c")

        assert table.columns == ()
        assert [column for column, _why in table.uncompared] == ["fk_p"]


class TestOptOuts:
    def test_subset_and_skip(self) -> None:
        ddl = "CREATE TABLE app.a (k text PRIMARY KEY); CREATE TABLE app.b (k text PRIMARY KEY);\n"
        seeds = {"s.sql": "INSERT INTO app.a VALUES ('1');\nINSERT INTO app.b VALUES ('1');\n"}

        scope = _scope(
            ddl,
            seeds,
            tables={
                "app.a": {"mode": "subset", "reason": "grows in production"},
                "app.b": {"skip": True, "reason": "per environment"},
            },
        )

        assert [(t.relation.qualified, t.mode) for t in scope.tables] == [("app.a", "subset")]
        assert scope.skipped == (("app.b", "per environment"),)

    def test_an_entry_that_matches_nothing_is_reported(self) -> None:
        scope = _scope(
            TRINITY,
            {"s.sql": "INSERT INTO catalog.tb_unit (id, identifier) VALUES ('a', 'b');\n"},
            tables={"catalog.tb_gone": {"key": ["id"]}},
        )

        assert scope.unused == (
            "seed_drift.tables.catalog.tb_gone matches no table the seed writes: remove it",
        )


class TestWhatTheReleaseReviewFound:
    """Each a shape a reviewer built against the first cut, and what it got wrong."""

    def test_a_positional_insert_maps_values_onto_every_column(self) -> None:
        """``VALUES (DEFAULT, …)`` leaves the identity to PostgreSQL: it is no key."""
        ddl = (
            "CREATE TABLE app.t (id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,"
            " code text NOT NULL UNIQUE, label text);\n"
        )
        scope = _scope(ddl, {"s.sql": "INSERT INTO app.t VALUES (DEFAULT, 'c', 'l');\n"})

        table = _table(scope, "app.t")
        assert (table.key, table.key_basis) == ((Field("code"),), "unique")
        assert table.columns == (Field("label"),)

    def test_a_seed_insert_select_cannot_prove_its_key_is_not_computed(self) -> None:
        ddl = "CREATE TABLE app.t (id uuid PRIMARY KEY, code text);\n"
        seeds = {"s.sql": "INSERT INTO app.t (id, code) SELECT gen_random_uuid(), 'x';\n"}

        scope = _scope(ddl, seeds)

        assert [e.table for e in scope.not_compared] == ["app.t"]

    def test_a_column_one_statement_leaves_to_its_default_is_not_compared(self) -> None:
        ddl = "CREATE TABLE app.t (id uuid DEFAULT gen_random_uuid(), code text NOT NULL UNIQUE);\n"
        seeds = {
            "s.sql": "INSERT INTO app.t (id, code) VALUES ('a', 'x');\n"
            "INSERT INTO app.t (code) VALUES ('y');\n"
        }

        table = _table(_scope(ddl, seeds), "app.t")

        assert table.columns == ()
        assert [column for column, _why in table.uncompared] == ["id"]

    def test_a_do_block_makes_the_scope_incomplete(self) -> None:
        ddl = "CREATE TABLE app.t (code text PRIMARY KEY);\n"
        seeds = {"s.sql": "DO $$ BEGIN INSERT INTO app.t VALUES ('a'); END $$;\n"}

        [entry] = _scope(ddl, seeds).not_compared

        assert (entry.table, entry.where) == ("seed", "s.sql:1")
        assert "a DO block may write rows" in entry.reason

    def test_a_ddl_statement_in_a_seed_file_writes_no_row(self) -> None:
        """A staging table's DDL the path rule files as a seed is not a hidden writer."""
        ddl = "CREATE TABLE app.t (code text PRIMARY KEY);\n"
        seeds = {"s.sql": "CREATE TABLE app.u (k int);\nINSERT INTO app.t VALUES ('a');\n"}

        assert _scope(ddl, seeds).not_compared == ()

    def test_no_seeded_table_is_never_a_pass(self) -> None:
        [entry] = _scope("CREATE TABLE app.t (k int);\n", {}).not_compared

        assert "nothing was compared" in entry.reason

    def test_a_binary_copy_keeps_its_table_in_scope(self) -> None:
        ddl = "CREATE TABLE app.t (code text PRIMARY KEY);\n"
        seeds = {"s.sql": "COPY app.t (code) FROM stdin WITH (FORMAT binary);\n\\.\n"}

        scope = _scope(ddl, seeds)

        assert [e.table for e in scope.not_compared] == ["app.t"]

    def test_a_staging_keyed_entry_sets_the_mode(self) -> None:
        scope = _scope(
            TestStagingResolution.DDL,
            {"s.sql": "INSERT INTO prep_seed.tb_unit VALUES ('a', 'kilogram');\n"},
            tables={"prep_seed.tb_unit": {"mode": "subset", "reason": "grows in production"}},
        )

        assert _table(scope, "catalog.tb_unit").mode == "subset"
        assert scope.unused == ()

    def test_a_composite_foreign_key_into_generated_keys_is_not_compared(self) -> None:
        ddl = """
CREATE TABLE app.p (pk bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, code text UNIQUE NOT NULL);
CREATE TABLE app.j (fk_a bigint REFERENCES app.p (pk), fk_b bigint REFERENCES app.p (pk),
    PRIMARY KEY (fk_a, fk_b));
CREATE TABLE app.c (code text PRIMARY KEY, fk_a bigint, fk_b bigint,
    FOREIGN KEY (fk_a, fk_b) REFERENCES app.j (fk_a, fk_b));
"""
        seeds = {
            "s.sql": "INSERT INTO app.p (code) VALUES ('x');\n"
            "INSERT INTO app.j VALUES (1, 1);\n"
            "INSERT INTO app.c VALUES ('c', 1, 1);\n"
        }

        table = _table(_scope(ddl, seeds), "app.c")

        assert table.columns == ()
        assert {column for column, _why in table.uncompared} == {"fk_a", "fk_b"}

    def test_money_is_not_compared(self) -> None:
        ddl = "CREATE TABLE app.t (code text PRIMARY KEY, price money);\n"
        scope = _scope(ddl, {"s.sql": "INSERT INTO app.t VALUES ('a', 1);\n"})

        assert [c for c, _why in _table(scope, "app.t").uncompared] == ["price"]
